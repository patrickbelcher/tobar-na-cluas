// scripts/fetch-fonts.mjs
// One-off: download the site's Google Fonts as local .woff2 files and write public/css/fonts.css.
// Run from the repo root:  node scripts/fetch-fonts.mjs
import { mkdir, writeFile } from "node:fs/promises";

// Only the styles custom.css actually uses. If you start using another weight or
// italic, add it here and run the script again.
const CSS_URL = "https://fonts.googleapis.com/css2"
  + "?family=Averia+Serif+Libre:ital,wght@0,400;1,300;1,400;1,700"
  + "&family=SUSE+Mono:wght@600"
  + "&display=swap";

// Latin + Latin Extended cover English, Irish and other European accents.
// Text in other scripts (e.g. Japanese in a tracklist) falls back to a system font,
// exactly as it does with Google's hosting.
const KEEP = new Set(["latin", "latin-ext"]);

// Google only sends .woff2 to browsers it recognises, so identify as current Chrome
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36";

const css = await (await fetch(CSS_URL, { headers: { "User-Agent": UA } })).text();

// Google's CSS is a list of "/* subset */ @font-face { ... }" blocks
const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g)];
if (!blocks.length) throw new Error("No @font-face blocks found. Google replied:\n" + css.slice(0, 500));

await mkdir("public/fonts", { recursive: true });
let out = "/* Self-hosted Google Fonts. Generated by scripts/fetch-fonts.mjs: edit that, not this. */\n\n";

for (const [, subset, block] of blocks) {
  if (!KEEP.has(subset)) continue;
  const family = block.match(/font-family:\s*'([^']+)'/)[1];
  const style = block.match(/font-style:\s*(\w+)/)[1];
  const weight = block.match(/font-weight:\s*(\d+)/)[1];
  const url = block.match(/url\((https:[^)]+\.woff2)\)/)[1];
  const file = `${family.toLowerCase().replace(/\s+/g, "-")}-${weight}-${style}-${subset}.woff2`;

  const data = Buffer.from(await (await fetch(url)).arrayBuffer());
  await writeFile(`public/fonts/${file}`, data);

  out += `/* ${subset} */\n` + block.replace(url, `/fonts/${file}`) + "\n\n";
  console.log(`saved public/fonts/${file} (${Math.round(data.length / 1024)} KB)`);
}

await writeFile("public/css/fonts.css", out);
console.log("wrote public/css/fonts.css");